# Build a lookup dict for quick access
RISK_SCENARIO_MAP = {s["key"]: s for s in RISK_SCENARIOS}

# ── Context builder ───────────────────────────────────────────────────────────

def build_cfo_context(kpi_map: dict[str, Kpi], alerts_df: pd.DataFrame) -> dict:
    return {
        "kpis": {
            k: {"value": v.value, "unit": v.unit, "status": v.status, "delta": v.delta_1d}
            for k, v in kpi_map.items()
        },
        "crit_count": int((alerts_df["重要度"] == "CRIT").sum()),
        "warn_count":  int((alerts_df["重要度"] == "WARN").sum()),
    }


# ── Risk scenario response generator ─────────────────────────────────────────

def get_risk_scenario(scenario_key: str, ctx: dict) -> str:
    """Return formatted markdown for a risk scenario analysis."""
    s = RISK_SCENARIO_MAP.get(scenario_key)
    if s is None:
        return f"シナリオ '{scenario_key}' が見つかりません。"
    return _format_scenario(s, ctx)


def _format_scenario(s: dict, ctx: dict) -> str:
    kpis = ctx.get("kpis", {})
    sol  = kpis.get("solvency_ratio",  {}).get("value", 218.5)
    cr   = kpis.get("combined_ratio",  {}).get("value", 97.2)
    bop  = kpis.get("op_profit_ytd",   {}).get("value", 17.2)

    # Impact table
    table  = "| 指標 | 影響 | 変化幅（推定） | 理由 |\n"
    table += "|---|:---:|---|---|\n"
    for metric, direction, magnitude, reason in s["impacts"]:
        table += f"| {metric} | **{direction}** | {magnitude} | {reason} |\n"

    # Current values note
    current = (
        f"\n> **現在値（参考）** — SCR: {sol:.1f}%　｜　CR: {cr:.1f}%　｜　BOP: {bop:.1f}億円\n"
    )

    # Action items
    actions = "\n".join(f"{i+1}. {a}" for i, a in enumerate(s["actions"]))

    return (
        f"### {s['icon']} {s['label']}  —  リスクシナリオ分析\n\n"
        f"**シナリオ概要**\n\n{s['overview']}\n"
        + current
        + f"\n**財務指標への影響**\n\n{table}\n"
        f"**CFOとしての判断・対応アクション**\n\n{actions}"
    )


# ── Standard CFO insight ──────────────────────────────────────────────────────

def get_cfo_insight(question: str, ctx: dict) -> str:
    """Return formatted markdown for a standard CFO question."""
    kpis = ctx.get("kpis", {})
    sol  = kpis.get("solvency_ratio",   {}).get("value", 218.5)
    bop  = kpis.get("op_profit_ytd",    {}).get("value", 17.2)
    roe  = kpis.get("group_roe",        {}).get("value", 15.5)
    inv  = kpis.get("investment_return",{}).get("value", 3.4)
    exp  = kpis.get("expense_ratio",    {}).get("value", 31.1)
    cr   = kpis.get("combined_ratio",   {}).get("value", 97.2)
    crit = ctx.get("crit_count", 0)

    if "財務状況" in question or "主要リスク" in question:
        return _financial_status(sol, bop, roe, cr, crit)
    if "EIOPA" in question or "ソルベンシー報告" in question:
        return _eiopa_report(sol, bop)
    if "再保険" in question:
        return _reinsurance_cost(cr, bop)
    if "配当" in question or "自社株買い" in question or "資本効率" in question:
        return _capital_efficiency(sol, roe, bop)
    return _general_cfo(sol, bop, roe, inv, exp, cr)


