RISK_SCENARIO_MAP_CEO = {s["key"]: s for s in RISK_SCENARIOS_CEO}


# ── Context builder ───────────────────────────────────────────────────────────

def build_ceo_context(kpi_map: dict[str, Kpi], alerts_df: pd.DataFrame) -> dict:
    return {
        "kpis": {
            k: {"value": v.value, "unit": v.unit, "status": v.status, "delta": v.delta_1d}
            for k, v in kpi_map.items()
        },
        "crit_count": int((alerts_df["重要度"] == "CRIT").sum()),
        "warn_count":  int((alerts_df["重要度"] == "WARN").sum()),
    }


# ── Risk scenario response ────────────────────────────────────────────────────

def get_risk_scenario_ceo(scenario_key: str, ctx: dict) -> str:
    s = RISK_SCENARIO_MAP_CEO.get(scenario_key)
    if s is None:
        return f"シナリオ '{scenario_key}' が見つかりません。"
    return _format_ceo_scenario(s, ctx)


def _format_ceo_scenario(s: dict, ctx: dict) -> str:
    kpis = ctx.get("kpis", {})
    cr   = kpis.get("combined_ratio",  {}).get("value", 97.2)
    sol  = kpis.get("solvency_ratio",  {}).get("value", 218.5)
    gwp  = kpis.get("gwp_total_ytd",   {}).get("value", 142.6)

    table  = "| 影響領域 | 方向 | 見込み | 理由 |\n"
    table += "|---|:---:|---|---|\n"
    for area, direction, magnitude, reason in s["impacts"]:
        table += f"| {area} | **{direction}** | {magnitude} | {reason} |\n"

    current = (
        f"\n> **現在値（参考）** — GWP: {gwp:.1f}億円　｜　CR: {cr:.1f}%　｜　SCR: {sol:.1f}%\n"
    )

    actions = "\n".join(f"{i+1}. {a}" for i, a in enumerate(s["decisions"]))

    return (
        f"### {s['icon']} {s['label']}  —  CEO戦略分析\n\n"
        f"**シナリオ概要**\n\n{s['overview']}\n"
        + current
        + f"\n**経営・事業への影響**\n\n{table}\n"
        f"**CEOとしての優先判断・アクション**\n\n{actions}"
    )


